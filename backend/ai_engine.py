"""
Recommendation explanations and chatbot, powered by whichever AI provider
succeeds first (see ai_providers.py for the Gemini -> OpenRouter -> Groq
priority chain), with automatic fallback to the rule-based engine
(engine.py / chatbot.py) if every configured provider fails or none are
configured at all. The app never crashes because of an AI provider issue —
every failure is logged with its exact reason, and the response's `engine`
field always reports which engine actually produced the answer (a provider
name, or "rule-based").
"""
import json
import logging

import ai_providers
from config import config
from engine import recommend_scholarships, evaluate, why_recommended
from chatbot import handle_message as rule_based_chat

logger = logging.getLogger("scholarai.ai_engine")


def gemini_available():
    """Kept for backward compatibility with any code/logs referencing the
    old name. True if Gemini specifically is configured (not necessarily
    the first provider tried)."""
    return ai_providers.PROVIDERS["gemini"].is_configured()


def ai_available():
    """True if at least one real AI provider (any of Gemini/OpenRouter/Groq)
    is configured."""
    return ai_providers.any_provider_configured()


def active_provider_summary():
    """Human-readable summary of AI configuration for startup logging:
    which provider would be tried first, and what else is configured as
    fallback, or that none are configured (rule-based only)."""
    configured = [p.name for p in ai_providers.ordered_providers() if p.is_configured()]
    if not configured:
        return "rule-based only (no AI provider configured)"
    chain = " -> ".join(configured + ["rule-based"])
    return f"{configured[0]} (fallback chain: {chain})"


def get_recommendations(profile, scholarships, limit=10):
    """
    Returns the same shape as engine.recommend_scholarships(), but with the
    "why" explanation generated by an AI provider when available. The match
    score and eligibility itself always come from the deterministic
    rule-based engine (that's a factual eligibility computation, not
    something an LLM should be guessing at) — AI providers only enrich the
    natural-language explanation, and only when one succeeds.
    """
    base = recommend_scholarships(profile, scholarships, limit=limit)
    if not ai_available() or not base:
        return {"engine": "rule-based", "recommendations": base}

    try:
        summaries = []
        for r in base[:5]:  # cap prompt size
            s = r["scholarship"]
            summaries.append(
                f"- {s['name']} (provider: {s['provider']}, amount: {s['amount']}, "
                f"score: {r['score']}%, eligibility: {r['eligibility']}, "
                f"matched: {[m[0] for m in r['matched']]}, missing: {[m[0] for m in r['missing']]})"
            )
        prompt = (
            "You are a scholarship advisor. For each scholarship below, write ONE short, "
            "encouraging sentence (max 25 words) explaining why it was matched to this "
            "student, referencing the matched/missing criteria. Respond as a JSON array of "
            "strings, one per scholarship, in the same order, with no other text.\n\n"
            + "\n".join(summaries)
        )
        text, provider_name = ai_providers.call_with_fallback(prompt)
        cleaned = text.strip().strip("`")
        if cleaned.lower().startswith("json"):
            cleaned = cleaned[4:].strip()
        explanations = json.loads(cleaned)
        for i, r in enumerate(base[:5]):
            if i < len(explanations) and explanations[i]:
                r["why"] = explanations[i]
                r["why_source"] = provider_name
        return {"engine": provider_name, "recommendations": base}
    except ai_providers.AllProvidersFailedError as e:
        logger.warning(f"Recommendations: {e}. Falling back to rule-based engine.")
        return {"engine": "rule-based", "recommendations": base}
    except Exception as e:
        # Covers JSON-parsing issues, malformed AI output, etc. — an AI
        # provider succeeding at the HTTP level but returning unusable
        # content should degrade to rule-based, not break the request.
        logger.warning(f"Recommendations: AI response could not be used ({e}). Falling back to rule-based engine.")
        return {"engine": "rule-based", "recommendations": base}


def chat(message, profile, scholarships, history=None):
    """
    Returns (reply_text, engine_used). engine_used is the name of whichever
    provider actually answered ("gemini" / "openrouter" / "groq"), or
    "rule-based" if every configured provider failed or none are
    configured. Every provider failure is logged with its exact reason
    before moving on — never a silent fallback.
    """
    if not ai_available():
        return rule_based_chat(message, profile, scholarships), "rule-based"

    try:
        profile_summary = "No profile information available yet."
        if profile and profile["cgpa"] is not None:
            profile_summary = (
                f"Course: {profile['course']}, Branch: {profile['branch']}, CGPA: {profile['cgpa']}, "
                f"Category: {profile['category']}, State: {profile['state']}, "
                f"Annual family income: {profile['annual_family_income']}"
            )
        sch_list = "\n".join(
            f"- {s['name']} ({s['provider']}): amount {s['amount']}, deadline {s['application_deadline']}, "
            f"course {s['course']}, category {s['category']}, min CGPA {s['min_cgpa']}, "
            f"max income {s['max_family_income']}, documents: {s['required_documents']}"
            for s in scholarships[:25]
        )
        history_text = ""
        if history:
            history_text = "\n".join(f"{h['sender']}: {h['message']}" for h in history[-6:])

        prompt = (
            "You are ScholarAI, a helpful and concise scholarship assistant for a student "
            "portal. Use ONLY the scholarship data provided below to answer questions about "
            "specific scholarships — do not invent scholarships, amounts, or deadlines that "
            "aren't listed. For general questions unrelated to scholarships, answer helpfully "
            "and briefly as a knowledgeable assistant. Keep answers under 120 words.\n\n"
            f"Student profile:\n{profile_summary}\n\n"
            f"Available scholarships:\n{sch_list}\n\n"
            f"Recent conversation:\n{history_text}\n\n"
            f"Student's new message: {message}\n\nYour reply:"
        )
        reply, provider_name = ai_providers.call_with_fallback(prompt)
        return reply, provider_name
    except ai_providers.AllProvidersFailedError as e:
        logger.warning(f"Chatbot: {e}. Falling back to rule-based engine.")
        return rule_based_chat(message, profile, scholarships), "rule-based"
    except Exception as e:
        logger.warning(f"Chatbot: unexpected error using AI provider ({e}). Falling back to rule-based engine.")
        return rule_based_chat(message, profile, scholarships), "rule-based"
